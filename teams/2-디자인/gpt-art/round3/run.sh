#!/bin/bash
# 3차: 전투용 스프라이트 시험(3명), 외계인·보스, 전장 방, 화폐 바탕
D="$(cd "$(dirname "$0")" && pwd)"; R1="$D/../round1"
STYLE="첨부한 그림과 같은 그림체(진지한 판타지 게임 일러스트, 깔끔한 셀 셰이딩, 굵은 어두운 외곽선). 글자·로고·워터마크 없음."
# 사용법: job 이름 "지시문" [참고그림...]  (-i 뒤에 지시문이 오면 그림으로 먹혀서 순서 고정)
job(){ name=$1; prompt=$2; shift 2; imgs=(); for f in "$@"; do imgs+=(-i "$f"); done
  [ -n "$ONLY" ] && [[ " $ONLY " != *" $name "* ]] && return
  codex exec --skip-git-repo-check --color never -s workspace-write -C "$D" "${imgs[@]}" -o "$D/result-$name.md" -- "$prompt" < /dev/null > "$D/codex-$name.log" 2>&1; echo "$name done"; }

job sprites "첨부한 장수 3명(한국·일본·독일)을 게임 전투 화면용 작은 스프라이트로 다시 그려서 이미지 생성 기능으로 저장해 주세요: sprite-korea.png, sprite-japan.png, sprite-germany.png.
- 위에서 비스듬히 내려다보는 고정 방 액션 게임(상하좌우에서 적이 오는 게임)에 쓸 캐릭터예요. 정면(아래쪽)을 보는 모습.
- 화면에서 64~96px로 작게 보여도 알아보게: 머리와 투구가 크고 몸이 작은 약 2.5등신 비율, 외곽선 더 굵게, 디테일은 단순하게. 원본의 갑옷·투구·무기·색은 그대로 유지.
- $STYLE 1024x1024, 배경 완전 투명, 가운데 배치. 얼굴은 투구로 가리고 과장·희화화 금지." "$R1/korea.png" "$R1/japan.png" "$R1/germany.png"

job aliens "지구를 침공한 외계인 적 캐릭터 3종을 이미지 생성 기능으로 만들어 저장해 주세요. $STYLE 각각 1024x1024, 배경 완전 투명, 위에서 비스듬히 내려다본 시점, 정면.
- alien-grunt.png: 작고 빠른 기본 외계인. 형광 보라색 몸, 다리 여러 개, 근접 공격형
- alien-shooter.png: 원거리에서 에너지 탄을 쏘는 외계인. 형광 초록색, 팔에 발사 기관
- alien-boss.png: 거대한 외계인 보스(매 라운드 나오는 같은 보스). 보라·초록 발광, 갑각 장갑, 위협적이지만 징그럽거나 잔인하지 않게(피·내장 없음)
- 첨부한 인간 장수들과 확실히 구분되는 형광색과 생물·기계 혼합 느낌." "$R1/preview.png"

job room "고정된 한 화면짜리 전장 방 배경을 이미지 생성 기능으로 만들어 room.png로 저장해 주세요. $STYLE
- 1920x1080 가로, 바로 위에서 내려다본 시점. 캐릭터·적 없이 바닥과 벽만.
- 외계인 침공을 받은 지구의 성채 안뜰 느낌: 가운데는 돌바닥이 넓게 비어 있고(전투 공간), 가장자리에 돌벽.
- 위·아래·왼쪽·오른쪽 벽 가운데에 하나씩, 총 4개의 문(외계인이 들어오는 입구)이 있고 문틈에 보라·초록 외계 빛이 새어 나옴.
- 바닥은 너무 복잡하지 않게(캐릭터가 잘 보이도록 어둡고 차분한 톤)." "$R1/preview.png"

job currency "게임 아이템용 화폐 바탕 그림 2장을 이미지 생성 기능으로 만들어 저장해 주세요. 진지한 판타지 게임 아이콘 스타일, 굵은 어두운 외곽선, 셀 셰이딩, 글자·숫자·기호·인물·국가 상징 전혀 없음(나중에 코드로 기호를 넣을 거예요). 각각 512x512, 배경 완전 투명.
- coin-blank.png: 빛나는 금화 한 개, 정면, 가운데 넓은 빈 원형 공간(기호를 넣을 자리), 테두리 장식만
- note-blank.png: 지폐 한 장을 살짝 접힌 모양, 초록·금빛, 가운데 빈 직사각형 공간, 테두리 무늬만. 실제 지폐와 닮지 않게"
