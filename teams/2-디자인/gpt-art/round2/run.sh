#!/bin/bash
# 27명을 9명씩 3번 나눠서 GPT에 생성 요청
D="$(cd "$(dirname "$0")" && pwd)"
REF="$D/../round1/preview.png"
for b in 1 2 3; do
  s=$(( (b-1)*9 + 1 )); e=$(( b*9 ))
  LIST=$(sed -n "${s},${e}p" "$D/countries.tsv" | awk -F'\t' '{printf "- %s.png: %s — 갑옷·투구: %s / 무기: %s / 포인트 색: %s\n",$1,$2,$3,$4,$5}')
  codex exec --skip-git-repo-check --color never -s workspace-write -C "$D" -i "$REF" -o "$D/result-$b.md" "첨부한 그림은 이미 확정된 웹게임 장수 캐릭터 3명(한국·일본·독일)이에요. 이 3명과 **완전히 같은 그림체**로 아래 캐릭터 이미지를 이미지 생성 기능으로 하나씩 만들어 이 폴더에 PNG로 저장해 주세요.

같은 그림체 기준 (반드시 맞추기):
- 진지한 판타지 게임 일러스트, 깔끔한 셀 셰이딩, 굵은 어두운 외곽선, 세밀한 갑옷 묘사
- 전신, 정면을 향해 무기를 든 당당한 자세, 첨부 그림과 같은 크기·비율·위치
- 배경 완전 투명, 1024x1024 정사각형, 가장자리 투명 여백
- 얼굴은 투구·면갑·가리개로 대부분 가려서 인종적 외모가 드러나지 않게. 과장·희화화 금지
- 모두 똑같이 멋있고 강해 보이게. 글자·로고·워터마크 없음
- **포인트 색(국기 색)을 망토·장식·깃털에 뚜렷하게** 넣어서 작게 봐도 나라끼리 구분되게. 빨강 위주로 몰리지 않게

만들 캐릭터:
$LIST
다 만들면 result-$b.md에 파일 이름별로 크기와 투명 배경 여부를 표로 적어 주세요." < /dev/null > "$D/codex-$b.log" 2>&1
  echo "batch $b done: $(ls "$D"/*.png 2>/dev/null | wc -l) png"
done
